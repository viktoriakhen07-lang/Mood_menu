/* Смайлик для блюда вместо фото: ищем ключевые слова в названии, иначе берём по категории.
   Порядок правил важен: более конкретные стоят выше (например, «боул с лососем» — 🥗, а не 🍣). */
function dishEmoji(d) {
  const name = String(d.name || "").toLowerCase();
  const rules = [
    [/том ям|креветк/, "🍤"],
    [/боул/, "🥗"],
    [/лосос|сёмг|семг|рыб/, "🍣"],
    [/матча|чай/, "🍵"],
    [/кофе|капучино|латте|эспрессо|американо|раф|мокко/, "☕"],
    [/брауни/, "🍫"],
    [/какао|шоколад/, "🍫"],
    [/лимонад/, "🍋"],
    [/морс|сок|смузи|коктейл|фреш/, "🥤"],
    [/чизкейк|торт|эклер|пирожн|тирамису/, "🍰"],
    [/мороженое|пломбир/, "🍨"],
    [/круассан|булочк|выпечк/, "🥐"],
    [/фрукт/, "🍓"],
    [/блин|вафл/, "🥞"],
    [/шакшук|яичниц|омлет/, "🍳"],
    [/пицца/, "🍕"],
    [/бургер/, "🍔"],
    [/паста|спагетти/, "🍝"],
    [/лагман|лапш|бульон/, "🍜"],
    [/суп|борщ|шурпа/, "🍲"],
    [/салат/, "🥗"],
    [/сэндвич|бутерброд|тост/, "🥪"],
    [/стейк|мясо|кебаб|шашлык/, "🥩"],
    [/крыл|курин|курица/, "🍗"],
    [/картофел|фри/, "🍟"],
  ];
  for (const [re, emoji] of rules) if (re.test(name)) return emoji;
  if (d.category === "Напитки") return d.temp === "cold" ? "🥤" : "☕";
  return { "Десерты": "🍰", "Закуски": "🥗", "Супы": "🍲", "Основные блюда": "🍽️" }[d.category] || "🍴";
}
